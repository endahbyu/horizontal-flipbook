import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '..');
const BOOKS_DIR = path.join(ROOT, 'assets', 'books');
const OUT = path.join(ROOT, 'js', 'pages.js');

const COVER_FRONT = 'cover-front.webp';
const COVER_BACK = 'cover-back.webp';
const PAGE_RE = /^page-(\d{2})\.webp$/;

// One manifest per folder in assets/books/<bookId>/.
function scanBook(bookId) {
  const dir = path.join(BOOKS_DIR, bookId);
  const files = fs.readdirSync(dir);
  const base = `assets/books/${bookId}`;
  const pages = files
    .map((name) => [PAGE_RE.exec(name), name])
    .filter(([m]) => m)
    .map(([m, name]) => [parseInt(m[1], 10), name])
    .sort((a, b) => a[0] - b[0])
    .map(([, name]) => `${base}/${name}`);

  return {
    coverFront: files.includes(COVER_FRONT) ? `${base}/${COVER_FRONT}` : null,
    coverBack: files.includes(COVER_BACK) ? `${base}/${COVER_BACK}` : null,
    pages,
  };
}

function main() {
  if (!fs.existsSync(BOOKS_DIR)) {
    console.error(`Books directory not found: ${BOOKS_DIR}`);
    process.exit(1);
  }

  const bookIds = fs.readdirSync(BOOKS_DIR, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();

  const manifests = {};
  for (const id of bookIds) manifests[id] = scanBook(id);

  const out = [
    '// AUTO-GENERATED by tools/scan-pages.js — do not edit by hand.',
    `window.FLIPBOOK_MANIFESTS = ${JSON.stringify(manifests, null, 2)};`,
    '',
  ].join('\n');

  fs.writeFileSync(OUT, out, 'utf-8');
  for (const id of bookIds) {
    console.log(`${id}: ${manifests[id].pages.length} content page(s)`);
  }
  console.log(`Generated ${path.relative(ROOT, OUT)}.`);
}

main();
